#!/usr/bin/env bash
# Exercise 16: a generated lock file conflicts; resolve the source file and regenerate the lock.
EX_DIR=$(cd "$(dirname "$0")" && pwd)
source "$EX_DIR/../../scripts/lib.sh"
echo "Ćwiczenie 16-plik-generowany-lock: przygotowanie piaskownicy"
new_sandbox

write tools/lock.sh <<'EOF'
#!/usr/bin/env bash
# Generates deps.lock from deps.txt (like npm install / mvn / gradle --write-locks would).
# Never edit deps.lock by hand.
cd "$(dirname "$0")/.." || exit 1
body=$(grep -vE '^[[:space:]]*(#|$)' deps.txt | sort -u | while read -r dep; do
  printf '%s sha=%s\n' "$dep" "$(printf '%s' "$dep" | cksum | cut -d' ' -f1)"
done)
{
  echo "# generated by tools/lock.sh from deps.txt - do not edit"
  echo "# integrity=$(printf '%s\n' "$body" | cksum | cut -d' ' -f1)"
  printf '%s\n' "$body"
} > deps.lock
echo "deps.lock: $(printf '%s\n' "$body" | wc -l | tr -d ' ') dependencies"
EOF
chmod +x tools/lock.sh
write deps.txt <<'EOF'
# Project dependencies (group:artifact:version), one per line.
org.slf4j:slf4j-api:2.0.16
com.fasterxml.jackson.core:jackson-databind:2.18.2
org.junit.jupiter:junit-jupiter:5.11.4
EOF
./tools/lock.sh > /dev/null
commit "Add dependencies and lock file"

git checkout -q -b feature/guava
as_student
echo "com.google.guava:guava:33.3.1-jre" >> deps.txt
./tools/lock.sh > /dev/null
commit "Add Guava"
sed -e 's/jackson-databind:2.18.2/jackson-databind:2.18.3/' deps.txt > d.tmp && mv d.tmp deps.txt
./tools/lock.sh > /dev/null
commit "Bump jackson-databind to 2.18.3 (CVE fix)"
state_set feature_tip "$(git rev-parse HEAD)"

git checkout -q main
as "Piotr Zielinski" pzielinski
echo "org.postgresql:postgresql:42.7.4" >> deps.txt
./tools/lock.sh > /dev/null
commit "Add PostgreSQL driver"
sed -e 's/slf4j-api:2.0.16/slf4j-api:2.0.17/' deps.txt > d.tmp && mv d.tmp deps.txt
./tools/lock.sh > /dev/null
commit "Bump slf4j to 2.0.17"
state_set main_start "$(git rev-parse HEAD)"

setup_done
